// Reads the SQL drizzle-kit generated under `drizzle/` and writes it into a TS
// module. Run by `pnpm db:generate` immediately after `drizzle-kit generate`.
//
// Why embed rather than ship the folder: drizzle's own migrator takes a
// `migrationsFolder` path, which means a packaged app has to locate that folder
// at runtime - inside an asar, beside a portable exe, or in a dev tree, three
// different answers. Embedding makes the migration set part of the bundle, so
// there is exactly one answer and it cannot drift from the code that uses it.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const drizzleDir = join(pkgRoot, 'drizzle')
const outFile = join(pkgRoot, 'src', 'store', 'migrations.generated.ts')

/** @type {{ entries: Array<{ tag: string }> }} */
const journal = JSON.parse(readFileSync(join(drizzleDir, 'meta', '_journal.json'), 'utf8'))

const known = new Set(
  readdirSync(drizzleDir)
    .filter((f) => f.endsWith('.sql'))
    .map((f) => f.slice(0, -'.sql'.length))
)

const migrations = journal.entries.map((entry) => {
  if (!known.has(entry.tag)) {
    throw new Error(`journal references ${entry.tag}.sql but that file is missing`)
  }
  const sql = readFileSync(join(drizzleDir, `${entry.tag}.sql`), 'utf8')
  // drizzle-kit separates statements with this marker rather than a bare `;`,
  // because a `;` inside a trigger body or a default expression is not a
  // statement boundary. better-sqlite3 prepares one statement at a time.
  const statements = sql
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
  return { tag: entry.tag, statements }
})

const body = `// GENERATED by scripts/embed-migrations.mjs - do not edit.
// Source: drizzle/*.sql, produced by \`pnpm db:generate\`.

export interface EmbeddedMigration {
  tag: string
  statements: string[]
}

export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)}
`

writeFileSync(outFile, body)
console.log(`embedded ${migrations.length} migration(s) -> ${outFile}`)
